/**
 * Payment allocation through the waterfall (pure) -> LIQD / LIQD_SUSP / OVERPAY tags.
 * Only amounts due on or before the payment date are allocated. Order: the product's waterfall
 * for the account status (component codes by priority); installment-major when
 * oldestInstallmentFirst, otherwise component-major across installments.
 * Funding: a customer advance (ADV_APPLIED) is used before new cash, but never for suspended
 * interest, which is settled in cash through LIQD_SUSP. Cash left over follows
 * overpaymentTreatment: CUSTOMER_ADVANCE / AUTO_FUTURE_INSTALLMENTS -> OVERPAY,
 * PRINCIPAL_PREPAY -> extra PRIN_PAID (partial prepayment; the schedule is regenerated by the caller).
 */
const N = require('./num');
const S = require('./state');
const { clean } = require('./prepayment');
const { LoanError } = require('../errors');

const FEE_TAG = 'FEE_DOC';
const INSURANCE_CODE = 'INSURANCE_PREMIUM';

const tagFor = (code, inst, penaltyBooked) => {
  if (code === 'PRINCIPAL') return { event: 'LIQD', tag: 'PRIN_PAID' };
  if (code === 'PENALTY') return { event: 'LIQD', tag: penaltyBooked ? 'PENALTY' : 'PEN_CASH' };
  if (code === 'INTEREST') {
    if (inst.interestBucket === 'SUSPENDED') return { event: 'LIQD_SUSP', tag: 'SUSP_PAID' };
    if (inst.interestBucket === 'UNBOOKED') return { event: 'LIQD', tag: 'INT_CASH' };
    return { event: 'LIQD', tag: 'INT_PAID' };
  }
  if (code === INSURANCE_CODE) return { event: 'LIQD', tag: 'INS_PREM' };
  return { event: 'LIQD', tag: FEE_TAG };
};

/**
 * input: { state, amount, date, waterfall: [componentCode...], oldestInstallmentFirst,
 *          overpaymentTreatment, useAdvance?, penaltyBooked?, rounder }
 */
const allocatePayment = (input) => {
  const { state, date, rounder } = input;
  const order = input.waterfall || [];
  if (!order.length) throw new LoanError(400, 'No waterfall order for this account status');
  if (!rounder.isRounded(input.amount)) throw new LoanError(400, `Payment has more than ${rounder.decimals} decimals`);
  let cash = N.of(input.amount);
  let advance = input.useAdvance ? N.of(state.advanceBalance || 0) : N.ZERO;
  if (N.isNeg(cash)) throw new LoanError(400, 'Payment cannot be negative');

  const due = state.installments.filter(i => S.isDue(i, date));
  const slots = input.oldestInstallmentFirst === false
    ? order.flatMap(code => due.map(inst => ({ inst, code })))
    : due.flatMap(inst => order.map(code => ({ inst, code })));

  const allocations = [];
  const sums = { LIQD: {}, LIQD_SUSP: {} };
  let fromAdvance = N.ZERO;
  for (const { inst, code } of slots) {
    let open = S.outstandingOf(inst.components[code]);
    if (N.cmp(open, 0) <= 0) continue;
    const { event, tag } = tagFor(code, inst, input.penaltyBooked);
    let taken = N.ZERO;
    if (event === 'LIQD' && N.cmp(advance, 0) > 0) {
      const a = N.min(advance, open);
      advance = N.sub(advance, a); fromAdvance = N.add(fromAdvance, a); open = N.sub(open, a); taken = N.add(taken, a);
    }
    if (N.cmp(open, 0) > 0 && N.cmp(cash, 0) > 0) {
      const c = N.min(cash, open);
      cash = N.sub(cash, c); taken = N.add(taken, c);
    }
    if (N.isZero(taken)) continue;
    allocations.push({ installmentNo: inst.no, componentCode: code, amount: rounder.round(taken), event, tag });
    sums[event][tag] = N.add(sums[event][tag] || 0, taken);
  }

  const liqdCredits = N.sum(Object.values(sums.LIQD));
  const suspCash = N.sum(Object.values(sums.LIQD_SUSP));
  let excess = cash;
  let partialPrepayment = N.ZERO;
  if (N.cmp(excess, 0) > 0 && input.overpaymentTreatment === 'PRINCIPAL_PREPAY') {
    const notDue = N.sum(state.installments.filter(i => !S.isDue(i, date)).map(i => S.outstandingOf(i.components.PRINCIPAL)));
    partialPrepayment = N.min(excess, notDue);
    excess = N.sub(excess, partialPrepayment);
    sums.LIQD.PRIN_PAID = N.add(sums.LIQD.PRIN_PAID || 0, partialPrepayment);
  }

  const events = [];
  const liqdTotal = N.add(liqdCredits, partialPrepayment);
  if (!N.isZero(liqdTotal)) {
    events.push({ event: 'LIQD', tags: clean({ TOTAL_PAID: N.sub(liqdTotal, fromAdvance), ADV_APPLIED: fromAdvance, ...sums.LIQD }, rounder) });
  }
  if (!N.isZero(suspCash)) events.push({ event: 'LIQD_SUSP', tags: clean({ SUSP_PAID: suspCash }, rounder) });
  if (!N.isZero(excess)) {
    if (!['CUSTOMER_ADVANCE', 'AUTO_FUTURE_INSTALLMENTS', 'PRINCIPAL_PREPAY'].includes(input.overpaymentTreatment)) {
      throw new LoanError(400, `Unknown overpayment treatment ${input.overpaymentTreatment}`);
    }
    events.push({ event: 'OVERPAY', tags: clean({ OVERPAY: excess }, rounder) });
  }
  return {
    events,
    allocations,
    advanceUsed: rounder.round(fromAdvance),
    // Advance after this payment: what was there, minus what was used, plus new excess cash (OVERPAY)
    advanceRemaining: rounder.round(N.add(N.sub(state.advanceBalance || 0, fromAdvance), excess)),
    partialPrepayment: rounder.round(partialPrepayment),
    unallocatedCash: rounder.round(excess)
  };
};

// New state after allocations (used to chain scenarios in tests and previews)
const applyAllocations = (state, allocations) => ({
  ...state,
  installments: state.installments.map(inst => {
    const mine = allocations.filter(a => a.installmentNo === inst.no);
    if (!mine.length) return inst;
    const components = { ...inst.components };
    for (const a of mine) {
      const c = components[a.componentCode];
      components[a.componentCode] = { ...c, paid: N.toDecimal(N.add(c.paid || 0, a.amount), 4) };
    }
    return { ...inst, components };
  })
});

module.exports = { allocatePayment, applyAllocations };
